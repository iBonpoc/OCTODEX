const KEY = "octo.db.v5";
const fs = require("node:fs");
const LOG = "/tmp/claude-0/-home-user/3a751330-6626-5571-acd0-3f240b0a2968/scratchpad/zz-handoff-log.txt";
const log = (...a) => fs.appendFileSync(LOG, a.join(" ") + "\n");
exports.run = async (h) => {
  const p = h.page;
  log("==== width", p.viewportSize().width);
  await h.go("/today");
  await p.waitForFunction((k) => !!JSON.parse(localStorage.getItem(k) || "null")?.db?.jobs?.length, KEY, { timeout: 8000 });
  const orig = await p.evaluate((k) => JSON.parse(localStorage.getItem(k)), KEY);
  const base = orig.db.jobs[0];
  const cust = orig.db.customers.find((c) => c.id === (base.customerId ?? orig.db.properties.find((x) => x.id === base.propertyId)?.customerId));
  log("cust", cust.name, "seed done jobs:", orig.db.jobs.filter((j) => j.status === "done").map((j) => j.id + ":" + j.amountCents).join(","));
  const day = (d) => new Date(Date.now() + d * 864e5).toISOString();
  const inv = (id, x) => ({ id, customerId: cust.id, jobId: "jz", totalCents: 0, paidCents: 0, dueDate: day(7), kind: "final", ...x });
  const scen = async (name, jobs, invoices, role = "director", jobPage = true) => {
    const raw = JSON.parse(JSON.stringify(orig));
    raw.db.jobs = [...raw.db.jobs, ...jobs.map((j) => ({ ...base, status: "done", amountCents: 50000, ...j }))];
    raw.db.invoices = [...raw.db.invoices, ...invoices];
    await h.seed(KEY, raw);
    await h.seed("octo.role.v1", role);
    await h.go("/triage");
    await p.waitForTimeout(500);
    const t = await h.text();
    const hits = t.split(" | ").map((s, i, a) => [s, a[i + 1], a[i + 2]]).filter(([s]) => /счёт не выставлен|Просрочен|выполнена\?/.test(s) && s.includes(cust.name));
    log(`-- ${name} [${role}] triage:`, hits.length ? hits.map((x) => x.join(" / ")).join(" || ") : "(none)");
    await h.shot(name);
    if (jobPage) {
      await h.go("/job/" + jobs[0].id);
      await p.getByText("Деньги", { exact: true }).locator("visible=true").first().waitFor({ timeout: 8000 });
      const cta = (await h.text()).match(/Создать счёт на остаток[^|]*/);
      log("   cta:", cta ? cta[0] : "(no cta)");
      await p.getByText("Деньги", { exact: true }).locator("visible=true").first().click();
      await p.getByText(/Выставлено/).locator("visible=true").first().waitFor({ timeout: 8000 }).catch(() => log("   job page: no statement"));
      const jt = await h.text();
      const m = jt.match(/Ещё не выставлено[^|]*/);
      const i = jt.indexOf("Договор");
      log(`   job page: ${m ? m[0] : "(no «Ещё не выставлено»)"} :: ${jt.slice(i, i + 200)}`);
      await h.shot(name + "-job");
    }
    await h.go("/more");
    await p.waitForTimeout(300);
    const mt = await h.text();
    log(`   more: ${(mt.match(/Работы[^|]*\|[^|]*/) || ["?"])[0]} ; ${(mt.match(/К плану: \d+/) || ["no counter"])[0]}`);
  };
  await scen("noinv", [{ id: "jz" }], []);
  await scen("deposit", [{ id: "jz" }], [inv("a", { kind: "deposit", totalCents: 15000, paidCents: 15000 })]);
  await scen("dep-prog-full", [{ id: "jz" }], [inv("a", { kind: "deposit", totalCents: 15000, paidCents: 15000 }), inv("b", { kind: "progress", totalCents: 35000 })]);
  await scen("final-part", [{ id: "jz" }], [inv("a", { kind: "final", totalCents: 20000 })]);
  await scen("void", [{ id: "jz" }], [inv("a", { kind: "final", totalCents: 50000, void: true })]);
  await scen("over", [{ id: "jz" }], [inv("a", { kind: "final", totalCents: 60000, paidCents: 70000 })]);
  await scen("zero", [{ id: "jz", amountCents: 0 }], []);
  await scen("standalone", [{ id: "jz" }], [inv("a", { kind: "standalone", totalCents: 50000 })]);
  await scen("nokind", [{ id: "jz" }], [inv("a", { kind: undefined, totalCents: 50000 })]);
  await scen("several", [{ id: "jz" }, { id: "jz2", title: "Second 2048", amountCents: 30000 }, { id: "jz3", title: "Third", amountCents: 12345 }], []);
  await scen("overdue+part", [{ id: "jz" }], [inv("a", { kind: "deposit", totalCents: 20000, dueDate: day(-10) })]);
  for (const r of ["dispatcher", "tech", "sales"]) await scen("role-" + r, [{ id: "jz" }], [], r, false);
  // click opens the job, then invoice covers -> gone
  await scen("click", [{ id: "jz" }], [], "director", false);
  await h.go("/triage");
  await p.getByText(new RegExp(`${cust.name}: работа выполнена, счёт не выставлен`)).locator("visible=true").first().click();
  await p.waitForURL((u) => u.pathname === "/job/jz", { timeout: 8000 });
  log("click opened", new URL(p.url()).pathname);
  await h.seed("octo.role.v1", "director");
};
